// Synthetic preview: a valid annotation is selected by default; only its rules render.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.PW_CHANNEL || undefined,executablePath:process.env.PW_EXECUTABLE || undefined});
 const page=await browser.newPage({viewport:{width:1440,height:980}});
 const root=path.resolve(process.argv[2]),shots=path.resolve(process.argv[3]);fs.mkdirSync(shots,{recursive:true});
 page.setDefaultTimeout(15000);page.setDefaultNavigationTimeout(30000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=pathToFileURL(path.join(root,'site/index.html')).href;
 const direct=pathToFileURL(path.join(root,'versions/v0.1/content/prototype/create-order.html')).href;
 async function checkReader(scope){
   assert.equal(await scope.locator('.sr-state:visible').count(),1);
   assert.equal(await scope.locator('.sr-pin-selected').count(),1);
   assert.equal(await scope.locator('.sr-highlight').count(),1);
   assert.equal(await scope.locator('.sr-focused-rules [data-rule-id]').count(),1);
   assert.equal(await scope.locator('.sr-other-rules,[data-show-all]').count(),0);
   assert.equal(await scope.locator('#default-name').getAttribute('type'),'text');
   assert.equal(await scope.locator('#sr-handoff').isVisible(),false);
   await scope.locator('#sr-handoff-toggle').click();
   assert.equal(await scope.locator('#sr-handoff').isVisible(),true);
   await scope.locator('#sr-handoff-toggle').click();
   assert.match(await scope.locator('.sr-table-wrap').first().innerText(),/新建为空/);
   assert.match(await scope.locator('.sr-rules').innerText(),/名称必填/);
   assert.equal(await scope.locator('[data-rule-id="RULE-ORDER-NAME"]').count(),1);
   assert.equal(await scope.locator('.sr-rules [data-locate="INT-ORDER-NAME"]').count(),1);
   assert.equal(await scope.locator('.sr-focused-rules [data-locate]').count(),0);
   assert.equal(await scope.locator('.ps-panel,.ps-tools').count(),0);
   assert.equal(await scope.locator('.sr-pin').count(),5);
   await scope.getByRole('button',{name:'校验失败',exact:true}).click();
   await scope.locator('.sr-pin[data-interaction="INT-ORDER-INVALID"]').click();
   assert.deepEqual(await scope.locator('.sr-focused-rules [data-rule-id]').evaluateAll(nodes=>nodes.map(n=>n.dataset.ruleId)),['RULE-ORDER-INVALID','RULE-ORDER-NAME']);
   assert.equal(await scope.locator('.sr-related-controls').count(),1);
   assert.equal(await scope.locator('.sr-related-controls[open]').count(),0);
   assert.equal(await scope.locator('.sr-rules [data-locate="INT-ORDER-NAME"]').count(),1);
   await scope.locator('.sr-related-controls summary').click();
   await scope.locator('.sr-related-controls [data-locate="INT-ORDER-NAME"]').press('Enter');
   assert.equal(await scope.locator('.sr-pin-selected').getAttribute('data-interaction'),'INT-ORDER-NAME');
   await scope.getByRole('button',{name:'提交失败',exact:true}).click();
   assert.equal(await scope.locator('[data-ps-state="failed"]').isVisible(),true);
   assert.equal(await scope.locator('.sr-state-context-fold[open]').count(),0);
   assert.equal(await scope.locator('.sr-tabs button[aria-pressed="true"]:focus').count(),1);
   assert.doesNotMatch(await scope.locator('.sr-rules').innerText(),/失败后保留已填内容/);
   assert.doesNotMatch(await scope.locator('.sr-rules').innerText(),/提交中禁用/);
   await scope.locator('.sr-pin').last().click();
   assert.match(await scope.locator('.sr-rules').innerText(),/失败后保留已填内容/);
   assert.equal(await scope.locator('.sr-selected').count(),1);
   assert.equal(await scope.locator('.sr-focused-rules').count(),1);
   assert.equal(await scope.locator('.sr-other-rules[open]').count(),0);
   await scope.locator('.sr-pin[data-interaction="INT-ORDER-NAME"]').click();
   assert.equal(await scope.locator('[data-ps-state="failed"] .sr-highlight').count(),1);
   await scope.getByRole('button',{name:'展开状态对照'}).click();
   assert.equal(await scope.locator('.sr-state:visible').count(),5);
   assert.equal(await scope.locator('[data-rule-card="INT-ORDER-NAME"]').count(),1);
   await scope.locator('#sr-numbers').uncheck();assert.equal(await scope.locator('.sr-pin').count(),0);
   await scope.getByRole('button',{name:'返回单状态'}).click();
 }
 await page.route('https://**/*',route=>route.abort());
 try{
   await page.goto(direct);await checkReader(page);
   await page.locator('#sr-numbers').check();await page.screenshot({path:path.join(shots,'static-reader-desktop.png')});
   await page.reload();assert.equal(await page.locator('[data-ps-state="failed"]').isVisible(),true);
   await page.goto(base+'#/v/v0.1/prototype/create-order');
   const frame=page.frameLocator('iframe');await frame.locator('.sr-rules').waitFor();await checkReader(frame);
   await page.locator('.page-link[href="#/v/v0.1/_prd/functions"]').click({noWaitAfter:true});await page.locator('.prd-requirement').waitFor();
   assert.equal(await page.locator('.prd-module').innerText(),'订单管理');
   const ruleGroups=await page.locator('.prd-rule h4').allTextContents();
   assert.ok(ruleGroups.includes('数据与字段')&&ruleGroups.includes('操作与结果'));
   assert.match(await page.locator('.prd-requirement').innerText(),/名称必填/);
   assert.equal(await page.locator('.prd-fold[open]').count(),0);
   const download=page.waitForEvent('download');await page.locator('#prd-export').click();
   const md=fs.readFileSync(await(await download).path(),'utf8');
   assert.ok(md.includes('## 订单管理')&&md.includes('### 创建订单')&&md.includes('本次不做')&&md.includes('RULE-ORDER-FAILURE'));
   await page.locator('.prd-boundaries > summary').click();
   assert.doesNotMatch(await page.locator('.prd-boundaries').innerText(),/文字：|同布局的数值|独有补充/);
   const boundary=page.locator('[data-case-id="BC-ORDER-MAX"]');
   assert.match(await boundary.innerText(),/去除首尾空格后名称为40字/);
   assert.match(await boundary.innerText(),/长度校验通过/);
   assert.doesNotMatch(await boundary.innerText(),/BC-ORDER-MAX|AC-ORDER-MAX/);
   await boundary.getByRole('link',{name:'查看验收：AC-ORDER-MAX',exact:true}).click();
   await page.locator('[data-acceptance="AC-ORDER-MAX"]').waitFor();
   assert.equal(await page.locator('.prd-ac-fold[open]').count(),1);
   assert.match(await page.locator('[data-acceptance="AC-ORDER-MAX"]').innerText(),/40字/);
   await page.waitForFunction(()=>{const r=document.querySelector('[data-acceptance="AC-ORDER-MAX"]').getBoundingClientRect();return r.top>=0 && r.bottom<=innerHeight;});
   await page.screenshot({path:path.join(shots,'prd-desktop.png')});
   await page.goto(base+'#/v/v0.1/_prd/scope');
   const headings=await page.locator('.standard-prd h3').allTextContents();
   assert.ok(headings.indexOf('背景与目标')<headings.indexOf('本版功能清单'));
   await page.goto(base+'#/v/v0.1/_prd/appendix');
   assert.doesNotMatch(await page.locator('#content').innerText(),/启动本机 PRD 编辑器|不会假装|文件附件/);
   await page.setViewportSize({width:390,height:844});await page.goto(direct+'#state=failed');
   assert.equal(await page.locator('.sr-rules').isVisible(),true);
   assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   await page.screenshot({path:path.join(shots,'static-reader-mobile.png'),fullPage:true});
   assert.deepEqual(errors,[]);
   console.log('PASS static reader: direct + iframe, default selected annotation, 5 states, filtering, pins both ways, compare, persistence, standard PRD/export, mobile, no JS errors');
 }catch(error){fs.writeFileSync(path.join(shots,'failure.txt'),page.url()+'\n'+await page.locator('body').innerText({timeout:2000}).catch(()=>'<body unavailable>'));await page.screenshot({path:path.join(shots,'failure.png'),timeout:3000}).catch(()=>{});throw error;}finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
